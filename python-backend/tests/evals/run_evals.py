from __future__ import annotations

import asyncio
import os
import sys
import traceback
import uuid
from copy import deepcopy

from dotenv import load_dotenv
from pydantic import TypeAdapter

# Ensure app is in path
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "../..")))

from typing import Any, cast

from langchain_core.runnables import RunnableConfig

from app.modules.copilot.models import CopilotState
from app.modules.copilot import copilot_graph
from app.modules.graphs import operations
from app.modules.graphs.operations import GraphOperation
from app.modules.graphs.serializer import serialize_flow_to_code
from tests.evals.scenarios import SCENARIOS, EvalScenario

# Colors for terminal output
GREEN = "\033[92m"
RED = "\033[91m"
YELLOW = "\033[93m"
RESET = "\033[0m"
BOLD = "\033[1m"


async def run_scenario(scenario: EvalScenario) -> bool:
    print(f"{BOLD}Scenario:{RESET} {scenario.name}")
    print(f"  {BOLD}Prompt:{RESET} '{scenario.user_prompt}'")

    # Serialize initial state
    serialized_state = serialize_flow_to_code(scenario.initial_flow)

    thread_id = str(uuid.uuid4())
    config: RunnableConfig = {"configurable": {"thread_id": thread_id}}

    initial_state: CopilotState = {
        "trace_id": f"eval_{thread_id}",
        "graph_id": thread_id,
        "user_prompt": scenario.user_prompt,
        "serialized_state": serialized_state,
        "initial_flow_data": scenario.initial_flow.model_dump(mode="json"),
        "agent_checklist": None,
        "plan": None,
        "plan_approved": None,
        "operations": None,
        "validation_error": None,
        "apply_approved": None,
        "applied": None,
    }

    try:
        # Run copilot workflow
        final_state = await copilot_graph.ainvoke(cast(Any, initial_state), config)

        val_error = final_state.get("validation_error")
        if val_error:
            print(f"  {RED}[FAIL] Validation Error in Copilot Graph:{RESET} {val_error}")
            if final_state.get("operations"):
                print(f"  Generated Operations: {final_state.get('operations')}")
            return False

        ops = final_state.get("operations") or []
        if not ops:
            print(f"  {RED}[FAIL] No operations were generated by the Copilot planner.{RESET}")
            return False

        # Apply operations to local deepcopy of initial flow to verify assertions
        final_flow = deepcopy(scenario.initial_flow)
        validated_ops: list[GraphOperation] = [TypeAdapter(GraphOperation).validate_python(op) for op in ops]
        operations.apply_patch(final_flow, validated_ops)

        # Run scenario-specific assertions
        scenario.assert_fn(final_flow, ops)

        print(f"  {GREEN}[PASS] Scenario passed successfully!{RESET}")
        return True

    except Exception:
        print(f"  {RED}[FAIL] Exception raised during evaluation:{RESET}")
        traceback.print_exc()
        return False


async def main() -> None:
    import argparse

    # Parse arguments
    parser = argparse.ArgumentParser(description="Run copilot planner evaluations.")
    parser.add_argument("--model", type=str, default=None, help="The LLM model to evaluate.")
    args, unknown = parser.parse_known_args()

    # Load dotenv from base directory
    base_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), "../.."))
    load_dotenv(os.path.join(base_dir, ".env"))

    if args.model:
        os.environ["COPILOT_MODEL"] = args.model

    if not os.environ.get("GROQ_API_KEY"):
        print(f"{RED}Error: GROQ_API_KEY environment variable is not set.{RESET}")
        print("Please configure GROQ_API_KEY in your environment or python-backend/.env file.")
        sys.exit(1)

    print(f"\n{BOLD}================ Starting Copilot Planner Evaluations ================{RESET}\n")

    passed_count = 0
    total_count = len(SCENARIOS)

    for scenario in SCENARIOS:
        success = await run_scenario(scenario)
        print("-" * 70)
        if success:
            passed_count += 1

    print(f"\n{BOLD}Evaluation Run Summary:{RESET}")
    color = GREEN if passed_count == total_count else RED
    print(f"  {color}Passed {passed_count}/{total_count} scenarios.{RESET}\n")

    if passed_count < total_count:
        sys.exit(1)
    else:
        sys.exit(0)


if __name__ == "__main__":
    asyncio.run(main())
