# Colors for terminal output
GREEN = "\033[92m"
RED = "\033[91m"
YELLOW = "\033[93m"
CYAN = "\033[96m"
RESET = "\033[0m"
BOLD = "\033[1m"
DIM = "\033[2m"

BASE_DIR = Path(__file__).resolve().parent.parent.parent
LOGS_DIR = BASE_DIR / "logs" / "eval_runs"


class ScenarioResult:
    def __init__(self, scenario: EvalScenario) -> None:
        self.scenario = scenario
        self.passed: bool = False
        self.attempts: int = 1
        self.duration_seconds: float = 0.0
        self.prompt_tokens: int = 0
        self.completion_tokens: int = 0
        self.total_tokens: int = 0
        self.failure_reason: str | None = None
        self.validation_error: str | None = None
        self.operations: list[dict[str, Any]] | None = None


async def run_scenario(scenario: EvalScenario, verbose: bool = False) -> ScenarioResult:
    result = ScenarioResult(scenario)
    print(f"\n{BOLD}[Level {scenario.level}/10]{RESET} {scenario.name}", flush=True)
    print(f"  {DIM}Prompt:{RESET} '{scenario.user_prompt}'", flush=True)

    serialized_state = serialize_flow_to_code(scenario.initial_flow)
    thread_id = str(uuid.uuid4())
    config: RunnableConfig = {"configurable": {"thread_id": thread_id}}

    initial_state: CopilotState = {
        "trace_id": f"eval_{thread_id}",
        "graph_id": thread_id,
        "model": os.environ.get("COPILOT_MODEL", "gemini-3.5-flash-lite"),
        "user_prompt": scenario.user_prompt,
        "serialized_state": serialized_state,
        "initial_flow_data": scenario.initial_flow.model_dump(mode="json"),
        "plan": None,
        "operations": None,
        "validation_error": None,
        "applied": None,
        "retry_count": 0,
        "messages": None,
    }

    start_time = time.perf_counter()

    try:
        final_state = await copilot_graph.ainvoke(cast(Any, initial_state), config)
        result.duration_seconds = round(time.perf_counter() - start_time, 2)
        result.attempts = final_state.get("retry_count", 0) + 1

        val_error = final_state.get("validation_error")
        if val_error:
            result.passed = False
            result.validation_error = str(val_error)
            result.failure_reason = f"Validation Error in Graph: {val_error}"
            print(f"  {RED}[FAIL] Validation Error in Copilot Graph:{RESET} {val_error}")
            return result

        ops = final_state.get("operations")
        result.operations = ops
        if not ops:
            result.passed = False
            result.failure_reason = "No operations were generated by the Copilot planner."
            print(f"  {RED}[FAIL] No operations were generated by the Copilot planner.{RESET}")
            return result

        # Apply operations to local flow copy to evaluate assertions
        final_flow = deepcopy(scenario.initial_flow)
        update_input = GraphUpdateInput.model_validate(ops)
        final_flow = apply_graph_update(final_flow, update_input)

        # Run scenario assertions
        scenario.assert_fn(final_flow, ops)

        result.passed = True
        attempt_note = " (Pass@1)" if result.attempts == 1 else f" {YELLOW}(Self-Healed: Pass@{result.attempts}){RESET}"
        print(f"  {GREEN}[PASS]{RESET} Scenario passed in {result.duration_seconds}s{attempt_note}", flush=True)
        return result

    except AssertionError as ae:
        result.duration_seconds = round(time.perf_counter() - start_time, 2)
        result.passed = False
        result.failure_reason = f"Assertion Failed: {ae}"
        print(f"  {RED}[FAIL] Assertion Failed:{RESET} {ae}", flush=True)
        if verbose:
            traceback.print_exc()
        return result
    except Exception as ex:
        result.duration_seconds = round(time.perf_counter() - start_time, 2)
        result.passed = False
        result.failure_reason = f"Exception: {ex}"
        print(f"  {RED}[FAIL] Exception raised during evaluation:{RESET} {ex}", flush=True)
        if verbose:
            traceback.print_exc()
        return result


def export_markdown_report(model: str, results: list[ScenarioResult]) -> Path:
    LOGS_DIR.mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now(UTC).strftime("%Y%m%d_%H%M%S")
    report_path = LOGS_DIR / f"eval_report_{model}_{timestamp}.md"

    total = len(results)
    passed = sum(1 for r in results if r.passed)
    pass_at_1 = sum(1 for r in results if r.passed and r.attempts == 1)
    pass_healed = sum(1 for r in results if r.passed and r.attempts > 1)
    avg_latency = round(sum(r.duration_seconds for r in results) / total, 2) if total > 0 else 0.0

    lines: list[str] = [
        "# Graphboard Copilot Evaluation Report",
        "",
        f"- **Model**: `{model}`",
        f"- **Timestamp**: `{datetime.now(UTC).isoformat()}`",
        f"- **Total Scenarios**: `{total}`",
        f"- **Pass Rate**: `{passed}/{total}` (**{round((passed / total) * 100, 1) if total else 0}%**)",
        f"- **Pass@1 (First Try)**: `{pass_at_1}/{total}`",
        f"- **Pass@k (Self-Healed)**: `{pass_healed}`",
        f"- **Average Duration**: `{avg_latency}s`",
        "",
        "## Detailed Results",
        "",
        "| Level | Scenario | Result | Attempts | Duration | Failure / Notes |",
        "| :---: | :--- | :---: | :---: | :---: | :--- |",
    ]

    for r in results:
        status = "✅ PASS" if r.passed else "❌ FAIL"
        notes = r.failure_reason or "All invariants satisfied"
        lines.append(
            f"| {r.scenario.level} | {r.scenario.name} | {status} | {r.attempts} | {r.duration_seconds}s | {notes} |"
        )

    lines.append("")
    with open(report_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    return report_path


def print_summary_table(model: str, results: list[ScenarioResult], report_path: Path) -> None:
    total = len(results)
    passed = sum(1 for r in results if r.passed)

    print("\n" + "=" * 80)
    print(f"{BOLD}{CYAN}                     EVALUATION SCORECARD ({model}){RESET}")
    print("=" * 80)
    print(f"{'Level':<7} {'Scenario':<35} {'Status':<10} {'Attempts':<10} {'Duration':<10}")
    print("-" * 80)

    for r in results:
        status_color = GREEN if r.passed else RED
        status_str = "PASS" if r.passed else "FAIL"
        print(
            f"{r.scenario.level:<7} {r.scenario.name[:34]:<35} {status_color}{status_str:<10}{RESET} {r.attempts:<10} {r.duration_seconds:<8}s"
        )

    print("-" * 80)
    pass_color = GREEN if passed == total else (YELLOW if passed > 0 else RED)
    print(
        f"{BOLD}Summary:{RESET} {pass_color}{passed}/{total} Passed ({round((passed / total) * 100, 1)}%){RESET} | Scorecard saved to: {report_path.name}\n"
    )


async def main() -> None:
    parser = argparse.ArgumentParser(description="Run Graphboard Copilot evaluations.")
    parser.add_argument("--model", type=str, default="gemini-3.5-flash-lite", help="The LLM model to evaluate.")
    parser.add_argument("--level", type=int, default=None, help="Run a specific level (1-10).")
    parser.add_argument("--delay", type=float, default=None, help="Delay in seconds between scenarios (defaults to 15s for 3.5 Flash).")
    parser.add_argument("--verbose", action="store_true", help="Print full exception stack traces.")
    args, _ = parser.parse_known_args()

    # Load dotenv from backend directory
    load_dotenv(BASE_DIR / ".env")

    os.environ["COPILOT_MODEL"] = args.model

    if not os.environ.get("GEMINI_API_KEY") and not os.environ.get("GROQ_API_KEY"):
        print(f"{RED}Error: GEMINI_API_KEY environment variable is not set.{RESET}")
        print("Please configure GEMINI_API_KEY in python-backend/.env.")
        sys.exit(1)

    effective_delay = args.delay
    if effective_delay is None:
        effective_delay = 15.0 if "3.5-flash" in args.model and "lite" not in args.model else 0.0

    scenarios_to_run = SCENARIOS
    if args.level is not None:
        scenarios_to_run = [s for s in SCENARIOS if s.level == args.level]
        if not scenarios_to_run:
            print(f"{RED}Error: No scenario found with level {args.level}. (Available: 1-10){RESET}")
            sys.exit(1)

    print(
        f"\n{BOLD}Starting Evaluation Suite on model: {CYAN}{args.model}{RESET} ({len(scenarios_to_run)} scenarios, sequential pacing: {effective_delay}s delay)\n"
    )

    results: list[ScenarioResult] = []
    for i, scenario in enumerate(scenarios_to_run):
        if i > 0 and effective_delay > 0:
            print(f"  {DIM}Pausing {effective_delay}s to respect API rate limits...{RESET}", flush=True)
            await asyncio.sleep(effective_delay)
        result = await run_scenario(scenario, verbose=args.verbose)
        results.append(result)

    report_path = export_markdown_report(args.model, results)
    print_summary_table(args.model, results, report_path)

    if any(not r.passed for r in results):
        sys.exit(1)
    sys.exit(0)


if __name__ == "__main__":
    asyncio.run(main())
